def crc_compensate(body, at, want):
    """Choose body[at:at+4] so that crc32(body) == want (CRC32 is affine over GF(2))."""
    body[at:at + 4] = bytes(4); base = zlib.crc32(body); cols = []
    for bit in range(32):
        body[at + bit // 8] = 1 << (bit % 8); cols.append(zlib.crc32(body) ^ base); body[at + bit // 8] = 0
    piv = {}
    for i, v in enumerate(cols):
        m = 1 << i
        for p in sorted(piv, reverse=True):
            if v >> p & 1: v ^= piv[p][0]; m ^= piv[p][1]
        if v: piv[v.bit_length() - 1] = (v, m)
    t, sol = want ^ base, 0
    for p in sorted(piv, reverse=True):
        if t >> p & 1: t ^= piv[p][0]; sol ^= piv[p][1]
    if t: sys.exit('error: CRC compensation failed')
    body[at:at + 4] = sol.to_bytes(4, 'little')

def version_of(stock):
    h = hashlib.sha256(stock).hexdigest()
    return next((v for v, d in VERSIONS.items() if d['sha'] == h), None)

def build(stock, chosen, ver):
    hdr, body = stock[:HDR], bytearray(stock[HDR:])
    groups = [g for g in ORDER if g in chosen]
    if 'load' in chosen or 'heat' in chosen: groups.append('ps')
    for g in groups:
        for off, old, new in VERSIONS[ver]['patches'][g]:
            old, new = bytes.fromhex(old), bytes.fromhex(new)
            if len(old) != len(new) or body[off:off + len(old)] != old:
                sys.exit(f'error: unexpected bytes at {0x08000000 + off:#x} ({g})')
            body[off:off + len(new)] = new
    want = struct.unpack_from('<I', hdr, 8)[0]
    crc_compensate(body, CRC_AT, want)
    assert zlib.crc32(body) == want
    return hdr + bytes(body)

def ask(prompt, default=''):
    try: v = input(f'{prompt}{f" [{default}]" if default else ""}: ').strip()
    except EOFError: v = ''
    return v or default

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('firmware', nargs='?', help='official B21_Pro_<version>.bin')
    ap.add_argument('--all', action='store_true', help='all patches (tune v1)')
    ap.add_argument('--patches', help='comma list of: ' + ', '.join(ORDER))
    ap.add_argument('-o', '--output')
    a = ap.parse_args()
    guided = not (a.firmware and (a.all or a.patches))
    fw = a.firmware or ask('Official firmware file', 'B21_Pro_3.10.bin')
    try: stock = open(fw, 'rb').read()
    except OSError as e: sys.exit(f'error: {e}')
    ver = version_of(stock)
    if not ver: sys.exit(f'error: {fw} is not an official B21 Pro image of ' + ', '.join(VERSIONS))
    if guided: print(f'Firmware version {ver}')
    if a.all: chosen = list(ORDER)
    elif a.patches: chosen = [p.strip() for p in a.patches.split(',') if p.strip()]
    else:
        print('\nPatches:'); [print(f'  {i + 1}  {k:7s} {INFO[k]}') for i, k in enumerate(ORDER)]
        v = ask('Choose numbers separated by commas, or "all"', 'all').lower()
        try: chosen = list(ORDER) if v == 'all' else [ORDER[int(x) - 1] for x in v.replace(' ', '').split(',') if x]
        except (ValueError, IndexError): sys.exit(f'error: bad choice {v!r}')
    bad = [c for c in chosen if c not in ORDER]
    if bad or not chosen: sys.exit(f'error: unknown or empty patch list {bad}')
    chosen = [k for k in ORDER if k in chosen]
    out = build(stock, chosen, ver)
    name = f'B21_Pro_{ver}_' + ('tune-v1' if chosen == ORDER else '-'.join(chosen)) + '.bin'
    dst = a.output or (ask('Output file', name) if guided else os.path.join(os.path.dirname(os.path.abspath(fw)), name))
    open(dst, 'wb').write(out)
    h = hashlib.sha256(out).hexdigest()
    note = f'= {PAPER[h]}, tested on paper' if h in PAPER else ('this combination not printed as such' if ver == '3.10' else f'{ver}: emulated only, never printed')
    print(f'\nwrote {dst}\nversion {ver}, patches: {", ".join(chosen)}\nsha256 {h}  ({note})')
    if 'curve' in chosen and ver in ('3.12', '3.13'): print('note: on this version the curve also applies to genuine gray rolls')
    if 'load' in chosen or 'heat' in chosen:
        print('print start: 00 01 00 00 00 00 <mode> 01 <load> <load0> <heat1bit>, 0 = stock')

if __name__ == '__main__':
    main()
